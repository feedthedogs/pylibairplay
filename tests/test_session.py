"""End-to-end control session: /info, pair-setup, control-channel flip."""
import hashlib, os, plistlib
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from pylibairplay import keys
from pylibairplay.pairing import tlv8
from pylibairplay.pairing.tlv8 import Tag
from pylibairplay.pairing.setup import FLAG_TRANSIENT, SRP_USERNAME
from pylibairplay.pairing.srp import N, g
from pylibairplay.rtsp.server import Request
from pylibairplay.session import ControlSession


def _req(method, uri, body=b""):
    return Request(method, uri, "RTSP/1.0", {"content-length": str(len(body))}, body)


def _mk_session():
    return ControlSession(Ed25519PrivateKey.generate(), "AA:BB:CC:DD:EE:FF",
                          info_provider=lambda: {"deviceid": "AA:BB:CC:DD:EE:FF", "features": 1})


def test_info_returns_binary_plist():
    s = _mk_session()
    resp = s.handle(_req("GET", "/info"))
    assert resp.status == 200
    assert plistlib.loads(resp.body)["deviceid"] == "AA:BB:CC:DD:EE:FF"


def _pad(x): return x.to_bytes((N.bit_length() + 7) // 8, "big")
def _Hi(*c):
    h = hashlib.sha512()
    for x in c: h.update(x)
    return int.from_bytes(h.digest(), "big")


def test_transient_pairing_flips_control_channel():
    s = _mk_session()
    pin = b"3939"
    m2 = tlv8.decode(s.handle(_req("POST", "/pair-setup", tlv8.encode({
        Tag.STATE: b"\x01", Tag.FLAGS: FLAG_TRANSIENT.to_bytes(4, "little")}))).body)
    B = int.from_bytes(m2[Tag.PUBLIC_KEY], "big"); salt = m2[Tag.SALT]
    a = int.from_bytes(os.urandom(32), "big"); A = pow(g, a, N)
    k = _Hi(_pad(N), _pad(g)); x = _Hi(salt, hashlib.sha512(SRP_USERNAME + b":" + pin).digest())
    u = _Hi(_pad(A), _pad(B)); S = pow((B - k * pow(g, x, N)) % N, a + u * x, N)
    K = hashlib.sha512(_pad(S)).digest()
    hn = int.from_bytes(hashlib.sha512(_pad(N)).digest(), "big")
    hg = int.from_bytes(hashlib.sha512(g.to_bytes(1,"big")).digest(), "big")
    M1 = hashlib.sha512((hn ^ hg).to_bytes(64, "big") + hashlib.sha512(SRP_USERNAME).digest()
                        + salt + _pad(A) + _pad(B) + K).digest()
    m4 = tlv8.decode(s.handle(_req("POST", "/pair-setup", tlv8.encode({
        Tag.STATE: b"\x03", Tag.PUBLIC_KEY: _pad(A), Tag.PROOF: M1}))).body)
    assert m4[Tag.STATE] == b"\x04"
    # control channel now armed with Control-Salt keys from K
    assert s.pairing_secret == K
    assert s.secure is not None
    # The receiver swaps the controller-oriented labels: it reads with Control-Write
    # and writes with Control-Read. A controller peer therefore reads with Control-Read.
    from pylibairplay.rtsp.secure import SecureChannel
    ctrl_read, ctrl_write = keys.control_channel_keys(K)
    peer = SecureChannel(read_key=ctrl_read, write_key=ctrl_write)  # controller orientation
    assert b"".join(peer.feed(s.secure.encrypt(b"hello"))) == b"hello"
    # and the receiver reads what the controller writes
    assert b"".join(s.secure.feed(peer.encrypt(b"ping"))) == b"ping"


def test_fp_setup_capture_route():
    """Legacy /fp-setup requests are routed to the fp_capture callback, which sees the
    exact request bytes and supplies the response."""
    seen = []
    s = ControlSession(Ed25519PrivateKey.generate(), "AA:BB:CC:DD:EE:FF",
                       info_provider=lambda: {}, fp_capture=lambda u, h, b: seen.append((u, b)) or b"\x01\x02")
    body = bytes.fromhex("46504c5903010200")  # 'FPLY' + mode
    resp = s.handle(Request("POST", "/fp-setup", "RTSP/1.0", {"x-apple-et": "32"}, body))
    assert resp.status == 200
    assert seen == [("/fp-setup", body)]
    assert resp.body == b"\x01\x02"  # response comes from the capture handler


def test_fp_setup_no_capture_is_empty_ok():
    s = ControlSession(Ed25519PrivateKey.generate(), "AA:BB:CC:DD:EE:FF", info_provider=lambda: {})
    resp = s.handle(Request("POST", "/fp-setup2", "RTSP/1.0", {}, b"x"))
    assert resp.status == 200 and resp.body == b""


def test_fp_phase1_cached_reply():
    """The receiver answers the fixed FairPlay v1 phase-1 request with the 142-byte reply
    generated by emulating the firmware whitebox, and captures anything else."""
    from pylibairplay.receiver import Receiver, FP_PHASE1_REPLIES

    req = bytes.fromhex("46504c590301010000000004020001bb")
    reply = FP_PHASE1_REPLIES[req.hex()]
    assert len(reply) == 142
    assert reply[:4] == b"FPLY" and reply[4:7].hex() == "030102"  # v3.1, phase-1 msg 2
    # All four reply-selector variants (request byte[14] = 0..3) are cached and distinct.
    sels = [f"46504c5903010100000000040200{n:02x}bb" for n in range(4)]
    assert all(k in FP_PHASE1_REPLIES for k in sels)
    assert len({FP_PHASE1_REPLIES[k] for k in sels}) == 4
    assert all(len(FP_PHASE1_REPLIES[k]) == 142 for k in sels)

    rx = Receiver(name="t", legacy=True)
    # known phase-1 request -> cached reply
    assert rx._fp_capture("/fp-setup", {"x-apple-et": "32"}, req) == FP_PHASE1_REPLIES[req.hex()]
    # unknown (e.g. phase-2 / session-specific) request -> empty (captured only)
    assert rx._fp_capture("/fp-setup", {"x-apple-et": "32"}, b"\x00\x01\x02") == b""


def test_fp_phase2_reply_is_pure():
    """A phase-2 request is answered in pure Python (no emulator) and both requests are
    remembered for the later ekey decrypt."""
    from pylibairplay.receiver import Receiver

    phase1 = bytes.fromhex("46504c590301010000000004020003bb")
    phase2 = bytes.fromhex("46504c590301030000000098" + "03" + "aa" * 131 + "bb" * 20)
    expected = bytes.fromhex("46504c590301040000000014" + "bb" * 20)

    rx = Receiver(name="t", legacy=True)
    assert rx._fp_emu is None
    rx._fp_capture("/fp-setup", {}, phase1)
    assert rx._fp_capture("/fp-setup", {}, phase2) == expected
    assert (rx._fp_last_phase1, rx._fp_last_phase2) == (phase1, phase2)


def test_legacy_advertisement_feature_set():
    from pylibairplay.discovery import ReceiverInfo, LEGACY_FEATURES
    ri = ReceiverInfo(name="x", device_id="AA:BB:CC:DD:EE:FF", public_key=b"\x00" * 32,
                      port=7000, features=int(LEGACY_FEATURES), legacy=True)
    txt = ri.txt_records()
    assert txt[b"features"] == b"0x527FFEE6,0x1E"
    assert txt[b"flags"] == b"0x4"


def test_control_setup_mirroring_returns_ports_and_stashes_ekey():
    """A legacy mirroring control SETUP (no streams) returns real event/timing ports and
    stashes ekey/eiv for the later FairPlay key decrypt."""
    import plistlib
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from pylibairplay.rtsp.server import Request

    s = ControlSession(Ed25519PrivateKey.generate(), "AA:BB:CC:DD:EE:FF",
                       info_provider=lambda: {},
                       on_control_setup=lambda req: {"eventPort": 7001, "timingPort": 7002})
    body = plistlib.dumps({
        "isScreenMirroringSession": True,
        "ekey": b"\x46\x50\x4c\x59" + b"\x11" * 68,
        "eiv": b"\x22" * 16,
        "timingPort": 50960,
    }, fmt=plistlib.FMT_BINARY)
    resp = s.handle(Request("SETUP", "rtsp://x/1", "RTSP/1.0",
                            {"Content-Type": "application/x-apple-binary-plist"}, body))
    assert resp.status == 200
    out = plistlib.loads(resp.body)
    assert out["eventPort"] == 7001 and out["timingPort"] == 7002
    assert s.fp_ekey.startswith(b"FPLY") and len(s.fp_eiv) == 16
